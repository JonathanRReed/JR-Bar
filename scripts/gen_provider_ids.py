#!/usr/bin/env python3
"""Generate the Swift fallback from the daemon's provider identity table."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from jrbar.provider_ids import ALIAS_IDS  # noqa: E402

OUTPUT = ROOT / "app/Sources/JRBarCore/ProviderID.swift"


def generated() -> str:
    rows = "\n".join(f'        "{alias}": "{provider}",' for alias, provider in sorted(ALIAS_IDS.items()))
    return '''// Generated by scripts/gen_provider_ids.py. Edit src/jrbar/provider_ids.py.
import Foundation

public enum ProviderID {
    public static let aliases: [String: String] = [
''' + rows + '''
    ]

    public static func canonical(_ value: String) -> String {
        let name = value.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let key = name.filter { !$0.isWhitespace && $0 != "-" && $0 != "_" }
        return aliases[key] ?? name
    }
}
'''


if __name__ == "__main__":
    if "--check" in sys.argv:
        raise SystemExit(0 if OUTPUT.read_text() == generated() else "Run scripts/gen_provider_ids.py")
    OUTPUT.write_text(generated())
